def idle_proc(duration=2.4):
    c = {
        "spine_02": lambda t: (0.025 * math.sin(TAU * t / duration), 0, 0),
        "spine_03": lambda t: (0.02 * math.sin(TAU * t / duration + 0.6), 0, 0),
        "neck_01": lambda t: (0.015 * math.sin(TAU * t / duration + 1.2), 0, 0),
        "upperarm_l": lambda t: (0.03 * math.sin(TAU * t / duration + 0.3), 0,
                                 0.04 + 0.01 * math.sin(TAU * t / duration)),
        "upperarm_r": lambda t: (0.03 * math.sin(TAU * t / duration + 0.9), 0,
                                 -0.04 - 0.01 * math.sin(TAU * t / duration)),
        "root": lambda t: (0.0, 0.012 * math.sin(TAU * t / duration), 0.0),
    }
    return _build("idle-proc", duration, c, loop=True)


def walk_proc(duration=1.0):
    w = TAU / duration  # one full stride cycle per loop
    c = {
        "thigh_l": lambda t: (-0.55 * math.sin(w * t), 0, 0),
        "thigh_r": lambda t: (0.55 * math.sin(w * t), 0, 0),
        "calf_l": lambda t: (0.7 * max(0.0, math.sin(w * t + 0.6)), 0, 0),
        "calf_r": lambda t: (0.7 * max(0.0, -math.sin(w * t + 0.6)), 0, 0),
        "upperarm_l": lambda t: (0.38 * math.sin(w * t), 0, 0.06),
        "upperarm_r": lambda t: (-0.38 * math.sin(w * t), 0, -0.06),
        "lowerarm_l": lambda t: (-0.25 - 0.1 * math.sin(w * t), 0, 0),
        "lowerarm_r": lambda t: (-0.25 + 0.1 * math.sin(w * t), 0, 0),
        "spine_02": lambda t: (0.04, 0, 0.03 * math.sin(w * t)),
        "root": lambda t: (0.0, -0.035 + 0.035 * math.cos(2 * w * t), 0.0),
    }
    return _build("walk-proc", duration, c, loop=True)


def run_proc(duration=0.7):
    w = TAU / duration
    c = {
        "thigh_l": lambda t: (-0.85 * math.sin(w * t), 0, 0),
        "thigh_r": lambda t: (0.85 * math.sin(w * t), 0, 0),
        "calf_l": lambda t: (1.1 * max(0.0, math.sin(w * t + 0.7)), 0, 0),
        "calf_r": lambda t: (1.1 * max(0.0, -math.sin(w * t + 0.7)), 0, 0),
        "upperarm_l": lambda t: (0.55 * math.sin(w * t), 0, 0.08),
        "upperarm_r": lambda t: (-0.55 * math.sin(w * t), 0, -0.08),
        "lowerarm_l": lambda t: (-1.15, 0, 0),
        "lowerarm_r": lambda t: (-1.15, 0, 0),
        "spine_01": lambda t: (0.10, 0, 0),
        "spine_02": lambda t: (0.08, 0, 0.02 * math.sin(w * t)),
        "neck_01": lambda t: (-0.12, 0, 0),
        "root": lambda t: (0.0, -0.05 + 0.05 * math.cos(2 * w * t), 0.0),
    }
    return _build("run-proc", duration, c, loop=True)


def crouch(duration=2.0):
    base = {
        "thigh_l": (0.95, 0, 0.06), "thigh_r": (0.95, 0, -0.06),
        "calf_l": (-1.15, 0, 0), "calf_r": (-1.15, 0, 0),
        "foot_l": (0.25, 0, 0), "foot_r": (0.25, 0, 0),
        "spine_01": (0.18, 0, 0), "spine_02": (0.14, 0, 0),
        "neck_01": (-0.18, 0, 0),
        "upperarm_l": (0.25, 0, 0.12), "upperarm_r": (0.25, 0, -0.12),
        "lowerarm_l": (-0.5, 0, 0), "lowerarm_r": (-0.5, 0, 0),
        "root": (0.0, -0.38, 0.0),
    }
    w = TAU / duration
    c = {j: (lambda t, v=v: (v[0] + 0.02 * math.sin(w * t), v[1], v[2]))
         for j, v in base.items() if j != "root"}
    c["root"] = lambda t: (0.0, -0.38 + 0.012 * math.sin(w * t), 0.0)
    return _build("crouch", duration, c, loop=True)


def aim_pose(duration=2.0):
    # Rifle aim stance: right arm shouldered forward, left hand supporting,
    # slight crouch, head into the sights. Loops with a micro sway.
    base = {
        "upperarm_r": (-1.30, -0.15, -0.10),
        "lowerarm_r": (-0.55, 0, 0),
        "upperarm_l": (-1.05, 0.55, 0.15),
        "lowerarm_l": (-0.9, -0.5, 0),
        "spine_01": (0.10, 0.12, 0),
        "spine_02": (0.08, 0, 0),
        "neck_01": (-0.10, -0.08, 0),
        "thigh_l": (0.28, 0, 0.05), "thigh_r": (0.22, 0, -0.05),
        "calf_l": (-0.34, 0, 0), "calf_r": (-0.28, 0, 0),
        "root": (0.0, -0.13, 0.0),
    }
    w = TAU / duration
    c = {j: (lambda t, v=v: (v[0] + 0.015 * math.sin(w * t + 0.5), v[1], v[2]))
         for j, v in base.items() if j != "root"}
    c["root"] = lambda t: (0.0, -0.13 + 0.008 * math.sin(w * t), 0.0)
    return _build("aim-pose", duration, c, loop=True)


