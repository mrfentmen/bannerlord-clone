def block(duration=0.6):
    guard = {
        "upperarm_l": (-1.15, 0.35, 0.25), "upperarm_r": (-1.15, -0.35, -0.25),
        "lowerarm_l": (-1.5, -0.4, 0), "lowerarm_r": (-1.5, 0.4, 0),
        "thigh_l": (0.35, 0, 0.05), "thigh_r": (0.35, 0, -0.05),
        "calf_l": (-0.45, 0, 0), "calf_r": (-0.45, 0, 0),
        "spine_02": (0.16, 0, 0),
        "root": (0.0, -0.14, 0.0),
    }
    neutral = {"root": (0.0, 0.0, 0.0)}
    keys = [
        (0.0, neutral),
        (0.15, guard),
        (0.45, guard),
        (duration, neutral),
    ]
    return _build_keyframed("block", duration, keys, loop=False)


def knockdown(duration=2.4):
    down = {
        "spine_01": (-0.55, 0, 0), "spine_02": (-0.45, 0, 0),
        "neck_01": (-0.35, 0, 0),
        "upperarm_l": (-0.9, 0, 0.5), "upperarm_r": (-0.9, 0, -0.5),
        "thigh_l": (0.25, 0, 0.1), "thigh_r": (0.15, 0, -0.1),
        "calf_l": (-0.35, 0, 0), "calf_r": (-0.25, 0, 0),
        "root": (0.0, -0.82, -0.15),
    }
    rising = {
        "thigh_l": (0.7, 0, 0.05), "thigh_r": (0.7, 0, -0.05),
        "calf_l": (-0.9, 0, 0), "calf_r": (-0.9, 0, 0),
        "spine_02": (0.25, 0, 0),
        "root": (0.0, -0.35, 0.0),
    }
    neutral = {"root": (0.0, 0.0, 0.0)}
    keys = [
        (0.0, neutral),
        (0.55, down),
        (1.5, down),
        (2.0, rising),
        (duration, neutral),
    ]
    return _build_keyframed("knockdown", duration, keys, loop=False)


def all_procedural():
    return [idle_proc(), walk_proc(), run_proc(), crouch(), aim_pose(),
            block(), knockdown()]
