"""Procedural animation clips: the zero-licensing fallback set.

Every clip here is synthesized from closed-form joint-angle curves, so there
is no source asset and no license to clear. Loop clips are bit-exact loops:
the pose is a sum of sinusoids with integer cycle counts over the clip
duration, so frame N-1 flows into frame 0 with no pop. One-shots start and end
in the neutral stance.

Conventions: angles are radians, XYZ euler order, applied as local joint
rotations on the shared skeleton. Y-up, metres. "root" entries are root
translation offsets from the bind pose.
"""

import math

import numpy as np

from extract import Clip, FPS

LICENSE = "generated by tools/anim/procedural.py; no source asset, no license needed"
SOURCE = "procedural (tools/anim/procedural.py)"

IDENTITY = (0.0, 0.0, 0.0)
TAU = 2.0 * math.pi


def _qx(a):
    return np.array([math.sin(a / 2), 0.0, 0.0, math.cos(a / 2)])


def _qy(a):
    return np.array([0.0, math.sin(a / 2), 0.0, math.cos(a / 2)])


def _qz(a):
    return np.array([0.0, 0.0, math.sin(a / 2), math.cos(a / 2)])


def euler_to_quat(rx, ry, rz):
    """XYZ euler order as a unit quaternion (x, y, z, w)."""
    q = np.array([0.0, 0.0, 0.0, 1.0])
    for single in (_qx(rx), _qy(ry), _qz(rz)):
        q = _mul(q, single)
    return q


def _mul(a, b):
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return np.array([
        aw * bx + ax * bw + ay * bz - az * by,
        aw * by - ax * bz + ay * bw + az * bx,
        aw * bz + ax * by - ay * bx + az * bw,
        aw * bw - ax * bx - ay * by - az * bz,
    ])


def _smooth(u):
    u = max(0.0, min(1.0, u))
    return u * u * (3.0 - 2.0 * u)


def _snap(v):
    # sin(k*TAU) is ~1e-16, not 0. Snap sub-1e-12 values so loop clips are
    # bit-exact at t=duration, not just close.
    return 0.0 if abs(v) < 1e-12 else v


def _pose(curves, t):
    """curves: {joint: fn(t) -> (rx, ry, rz)}. Returns {joint: quat}."""
    out = {}
    for joint, fn in curves.items():
        if joint == "root":
            continue
        rx, ry, rz = (_snap(v) for v in fn(t))
        if rx or ry or rz:
            out[joint] = euler_to_quat(rx, ry, rz)
    return out


def _root(curves, t):
    fn = curves.get("root")
    if not fn:
        return np.zeros(3)
    return np.array([_snap(v) for v in fn(t)], dtype=np.float64)


def _build(name, duration, curves, loop, root_policy="in-place"):
    nframes = max(2, int(round(duration * FPS)))
    frames = []
    for i in range(nframes):
        t = (i / nframes) * duration if loop else (i / (nframes - 1)) * duration
        frames.append({"rot": _pose(curves, t), "root": _root(curves, t)})
    clip = Clip(name, frames, loop, SOURCE, LICENSE, root_policy)
    # Loop clips are periodic: wrap the probe time so sample_fn(duration)
    # lands exactly on sample_fn(0), bit-for-bit.
    clip.sample_fn = (lambda t: {"rot": _pose(curves, t % duration),
                                "root": _root(curves, t % duration)}
                      if loop else
                      lambda t: {"rot": _pose(curves, t), "root": _root(curves, t)})
    clip.exact_duration = duration
    return clip


def _build_keyframed(name, duration, keys, loop, root_policy="as-authored"):
    """keys: list of (time, {joint: (rx,ry,rz) | 'root': (x,y,z)})."""
    keys = sorted(keys, key=lambda k: k[0])

    def at(t):
        if t <= keys[0][0]:
            return keys[0][1]
        if t >= keys[-1][0]:
            return keys[-1][1]
        for (t0, p0), (t1, p1) in zip(keys, keys[1:]):
            if t0 <= t <= t1:
                u = _smooth((t - t0) / (t1 - t0))
                joints = set(p0) | set(p1)
                out = {}
                for j in joints:
                    a = p0.get(j, IDENTITY if j != "root" else (0.0, 0.0, 0.0))
                    b = p1.get(j, IDENTITY if j != "root" else (0.0, 0.0, 0.0))
                    out[j] = tuple(x + (y - x) * u for x, y in zip(a, b))
                return out
        return keys[-1][1]

    nframes = max(2, int(round(duration * FPS)))
    frames = []
    for i in range(nframes):
        t = (i / nframes) * duration if loop else (i / (nframes - 1)) * duration
        pose = at(t)
        rot = {j: euler_to_quat(*pose[j]) for j in pose
               if j != "root" and any(pose[j])}
        root = np.array(pose.get("root", (0.0, 0.0, 0.0)), dtype=np.float64)
        frames.append({"rot": rot, "root": root})
    clip = Clip(name, frames, loop, SOURCE, LICENSE, root_policy)

    def sample_fn(t):
        pose = at(t)
        return {"rot": {j: euler_to_quat(*pose[j]) for j in pose
                        if j != "root" and any(pose[j])},
                "root": np.array(pose.get("root", (0.0, 0.0, 0.0)), dtype=np.float64)}

    clip.sample_fn = sample_fn
    clip.exact_duration = duration
    return clip


