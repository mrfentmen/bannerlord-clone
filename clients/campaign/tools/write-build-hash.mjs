#!/usr/bin/env node
/**
 * Writes the build hash for MASTER_PLAN task 29.
 *
 * Runs before `vite build` (see package.json). Emits two artifacts from one
 * hash:
 *   - `src/buildHash.ts`: the hash baked into the bundle, so the running app
 *     knows which build it is.
 *   - `public/build.json`: the hash served alongside the deployment, so the
 *     running app can poll for a newer one.
 *
 * The hash is a UTC timestamp to the second plus a short random suffix. It is
 * unique per build by construction and carries no claim about git state, which
 * this environment cannot reliably report.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");

function buildHash(now = new Date()) {
  const stamp = now
    .toISOString()
    .replace(/[-:]/g, "")
    .replace(/\..+/, "")
    .replace("T", "-");
  return `${stamp}-${randomBytes(3).toString("hex")}`;
}

export function writeBuildHash(hash = buildHash()) {
  const ts = `/**\n * Generated by tools/write-build-hash.mjs. Do not edit.\n */\nexport const BUILD_HASH = ${JSON.stringify(hash)};\n`;
  writeFileSync(join(ROOT, "src", "buildHash.ts"), ts);
  const json = JSON.stringify({ hash }, null, 2) + "\n";
  mkdirSync(join(ROOT, "public"), { recursive: true });
  writeFileSync(join(ROOT, "public", "build.json"), json);
  return hash;
}

const hash = writeBuildHash();
console.log(`build hash: ${hash}`);
